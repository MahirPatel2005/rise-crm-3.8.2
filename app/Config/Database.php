<?php

namespace Config;

use CodeIgniter\Database\Config;

/**
 * Database Configuration
 */
class Database extends Config
{
	/**
	 * The directory that holds the Migrations
	 * and Seeds directories.
	 *
	 * @var string
	 */
	public $filesPath = APPPATH . 'Database' . DIRECTORY_SEPARATOR;

	/**
	 * Lets you choose which connection group to
	 * use if no other is specified.
	 *
	 * @var string
	 */
	public $defaultGroup = 'default';

	/**
	 * The default database connection.
	 *
	 * @var array
	 */
	public $default = [
		'DSN'      => '',
		'hostname' => 'localhost',
		'username' => 'root',
		'password' => '',
		'database' => 'rise_crm',
		'DBDriver' => 'MySQLi',
		'DBPrefix' => 'rise_',
		'pConnect' => false,
		'DBDebug'  => (ENVIRONMENT !== 'production'),
		'charset'  => 'utf8',
		'DBCollat' => 'utf8_general_ci',
		'swapPre'  => '',
		'encrypt'  => false,
		'compress' => false,
		'strictOn' => false,
		'failover' => [],
		'port'     => 3306,
	];

	/**
	 * This database connection is used when
	 * running PHPUnit database tests.
	 *
	 * @var array
	 */
	public $tests = [
		'DSN'      => '',
		'hostname' => '127.0.0.1',
		'username' => '',
		'password' => '',
		'database' => ':memory:',
		'DBDriver' => 'SQLite3',
		'DBPrefix' => 'db_',  // Needed to ensure we're working correctly with prefixes live. DO NOT REMOVE FOR CI DEVS
		'pConnect' => false,
		'DBDebug'  => (ENVIRONMENT !== 'production'),
		'charset'  => 'utf8',
		'DBCollat' => 'utf8_general_ci',
		'swapPre'  => '',
		'encrypt'  => false,
		'compress' => false,
		'strictOn' => false,
		'failover' => [],
		'port'     => 3306,
	];

	//--------------------------------------------------------------------

	public function __construct()
	{
		parent::__construct();

		// Override default database settings with environment variables if they are set on Render
		if (getenv('DB_HOSTNAME')) {
			$this->default['hostname'] = getenv('DB_HOSTNAME');
		}
		if (getenv('DB_USERNAME')) {
			$this->default['username'] = getenv('DB_USERNAME');
		}
		if (getenv('DB_PASSWORD')) {
			$this->default['password'] = getenv('DB_PASSWORD');
		}
		if (getenv('DB_DATABASE')) {
			$this->default['database'] = getenv('DB_DATABASE');
		}
		if (getenv('DB_PORT')) {
			$this->default['port'] = (int)getenv('DB_PORT');
		}
		if (getenv('DB_ENCRYPT')) {
			$this->default['encrypt'] = (getenv('DB_ENCRYPT') === 'true' || getenv('DB_ENCRYPT') === '1') ? ['ssl_verify' => false] : false;
		}

		// Ensure that we always set the database group to 'tests' if
		// we are currently running an automated test suite, so that
		// we don't overwrite live data on accident.
		if (ENVIRONMENT === 'testing')
		{
			$this->defaultGroup = 'tests';
		}
	}

	//--------------------------------------------------------------------

}
